#!/usr/bin/env python3
"""文件体积守卫：提交前拦住「单文件过大」——agent 读不全就会改错的那类文件。

口径（来自 tidy skill / 本期视频）：单文件超过 5,000 token（≈ 20 KB，token 经验值按
字节/4 估算）就拒绝提交，报错要求按功能拆成小模块；lockfile、构建产物、自动生成文件
这类 agent 不会读的跳过。

为什么不挂 git hook（2026-11-08 实测）：本机主仓库是 colocated jj，`jj` 不执行 git
hooks——在临时仓库里放一个 `exit 1` 的 `.git/hooks/pre-commit`，`jj commit` 照常成功、
hook 未触发。所以门禁必须由 `tools/repo_guard.py` 调用；纯 git 仓库也可以单独把它挂到
pre-commit。

存量处理：基线（先试 `main` 书签，再试 `HEAD`）上就已经超标的文件只警告、不拦，列清单
交给用户后续拆分；新文件、或从 ≤ 上限长成 > 上限的才硬拦。这样不会卡住旧文件的正常小改。

用法：
    python tools/size_guard.py --paths src/a.py tests/b.py     # 提交前检查（被拦退出 1）
    python tools/size_guard.py --all-tracked                   # 只读盘点全仓超标文件
    python tools/size_guard.py --paths a.py --rev main         # 指定基线版本

退出码：0 通过（可有存量警告）；1 有拦截；2 环境错误。
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys

LIMIT_BYTES = 20_480          # ≈ 5,000 token（字节 / 4）
BYTES_PER_TOKEN = 4

SKIP_DIRS = {
    "dist", "build", "out", "node_modules", "vendor", "third_party",
    ".venv", "venv", ".git", "site-packages", "__pycache__",
    ".pytest_cache", ".ruff_cache", ".mypy_cache", "coverage", "htmlcov",
}
SKIP_NAMES = {
    "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "poetry.lock",
    "cargo.lock", "uv.lock", "go.sum", "composer.lock", "gemfile.lock",
}
SKIP_SUFFIXES = (
    ".lock", ".map", ".min.js", ".min.css", ".whl", ".tar", ".gz", ".zip",
    ".svg",
)
BINARY_EXTS = {
    ".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf", ".db", ".sqlite", ".sqlite3",
    ".7z", ".exe", ".dll", ".so", ".dylib", ".woff", ".woff2", ".ttf", ".otf",
    ".mp3", ".mp4", ".wav", ".webp", ".bmp", ".pyc", ".class", ".jar", ".bin",
}
GENERATED_MARKERS = (
    "@generated", "do not edit", "auto-generated", "autogenerated",
    "code generated", "此文件自动生成", "自动生成，请勿",
)
GENERATED_PROBE = 600        # 只看文件头：生成标记一般在最前面，避免正文提到这些词就被误跳过
NUL_PROBE = 8000


# ------------------------------------------------------------------ git 基础

def _git(args, cwd):
    result = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True,
                            encoding="utf-8", errors="replace")
    if result.returncode != 0:
        raise RuntimeError(
            f"git {' '.join(args)} 失败：{(result.stderr or result.stdout).strip()[:300]}"
        )
    return result.stdout or ""


def repo_root(start=None):
    """当前目录所在的 git 仓库根目录。"""
    return _git(["rev-parse", "--show-toplevel"], start or os.getcwd()).strip()


def tracked_paths(repo):
    """仓库已跟踪的文件（相对路径，正斜杠）。"""
    return [p for p in _git(["ls-files", "-z"], repo).split("\0") if p]


# ------------------------------------------------------------------ 判定

def estimate_tokens(size):
    """字节数换算 token 经验值（只用于报错提示，不追求精确）。"""
    return size // BYTES_PER_TOKEN


def skip_reason(path):
    """按路径判断：锁文件/构建产物/二进制扩展名 → 返回跳过原因。"""
    norm = path.replace("\\", "/")
    parts = [p for p in norm.split("/") if p]
    for part in parts[:-1]:
        if part.lower() in SKIP_DIRS:
            return f"目录 {part}/"
    name = (parts[-1] if parts else "").lower()
    if name in SKIP_NAMES:
        return "锁文件"
    for suffix in SKIP_SUFFIXES:
        if name.endswith(suffix):
            return f"后缀 {suffix}"
    if os.path.splitext(name)[1] in BINARY_EXTS:
        return "二进制"
    return None


def content_skip_reason(full_path):
    """按内容判断：二进制（NUL）或带生成标记。"""
    try:
        with open(full_path, "rb") as handle:
            head = handle.read(NUL_PROBE)
    except OSError:
        return "无法读取"
    if b"\x00" in head:
        return "二进制"
    probe = head[:GENERATED_PROBE].decode("utf-8", "ignore").lower()
    if any(marker in probe for marker in GENERATED_MARKERS):
        return "自动生成"
    return None


def baseline_size(repo, path, rev=None):
    """该路径在基线上的字节数；不存在返回 None（视为新文件）。"""
    revisions = [rev] if rev else ["main", "HEAD"]
    for revision in revisions:
        try:
            raw = _git(["cat-file", "-s", f"{revision}:{path}"], repo).strip()
        except RuntimeError:
            continue
        if raw.isdigit():
            return int(raw)
    return None


def classify(size, baseline, limit=LIMIT_BYTES):
    """返回 ok / warned（存量超标，不拦）/ blocked（新增长到超标，拦）。"""
    if size <= limit:
        return "ok"
    if baseline is not None and baseline > limit:
        return "warned"
    return "blocked"


def check_paths(repo, paths, rev=None, limit=LIMIT_BYTES):
    """检查一组仓库相对路径。

    返回 dict：blocked/warned 为 (path, size)；skipped 为 (path, reason)；checked 为
    实际检查的文本文件数。
    """
    result = {"blocked": [], "warned": [], "skipped": [], "checked": 0}
    for path in paths:
        norm = path.replace("\\", "/")
        full = os.path.join(repo, norm)
        if not os.path.isfile(full):
            continue  # 删除的文件不用查体积
        reason = skip_reason(norm) or content_skip_reason(full)
        if reason:
            result["skipped"].append((norm, reason))
            continue
        size = os.path.getsize(full)
        verdict = classify(size, baseline_size(repo, norm, rev), limit)
        result["checked"] += 1
        if verdict == "blocked":
            result["blocked"].append((norm, size))
        elif verdict == "warned":
            result["warned"].append((norm, size))
    return result


def oversized_tracked(repo, limit=LIMIT_BYTES):
    """全仓已跟踪文件里超过上限的（只读盘点，不区分存量/新增）。"""
    found = []
    for path in tracked_paths(repo):
        full = os.path.join(repo, path)
        if os.path.isfile(full) and os.path.getsize(full) > limit:
            found.append((path, os.path.getsize(full)))
    return sorted(found, key=lambda item: -item[1])


def fmt_size(size):
    return f"{size / 1024:.1f} KB"


# ------------------------------------------------------------------ CLI

def _report(res, limit):
    print(f"体积门禁：检查 {res['checked']} 个文本文件"
          f"（上限 {fmt_size(limit)} ≈ {estimate_tokens(limit)} token）")
    for path, size in res["warned"]:
        print(f"  [!] {path}  {fmt_size(size)} ≈ {estimate_tokens(size)} token"
              f" —— 存量超标（不拦），建议后续拆分")
    for path, size in res["blocked"]:
        print(f"  [x] {path}  {fmt_size(size)} ≈ {estimate_tokens(size)} token"
              f" —— 超标，请按功能拆成小模块后再提交")
    if res["skipped"]:
        shown = "、".join(f"{p}（{reason}）" for p, reason in res["skipped"][:6])
        tail = "" if len(res["skipped"]) <= 6 else f" 等 {len(res['skipped'])} 个"
        print(f"  跳过 {len(res['skipped'])} 个：{shown}{tail}")
    if res["blocked"]:
        print(f"体积门禁未通过：{len(res['blocked'])} 个文件超标")
        return 1
    print("体积门禁通过")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="文件体积守卫（>20KB≈5000 token 拒绝提交；存量只警告）"
    )
    parser.add_argument("--paths", nargs="*", default=[], help="要检查的路径（通常传本次变更文件）")
    parser.add_argument("--all-tracked", action="store_true", help="只读盘点全仓已跟踪超标文件")
    parser.add_argument("--repo", default=None, help="仓库根目录（默认取当前目录）")
    parser.add_argument("--rev", default=None, help="基线版本（默认先试 main、再试 HEAD）")
    args = parser.parse_args(argv)

    repo = os.path.abspath(args.repo) if args.repo else repo_root()
    limit = LIMIT_BYTES

    if args.all_tracked:
        found = oversized_tracked(repo, limit)
        if not found:
            print(f"全仓无超标文件（> {fmt_size(limit)} ≈ {estimate_tokens(limit)} token）")
            return 0
        print(f"全仓超标文件（> {fmt_size(limit)} ≈ {estimate_tokens(limit)} token，"
              f"只读盘点）：{len(found)} 个（存量，不拦提交）")
        for path, size in found:
            print(f"  [i] {path}  {fmt_size(size)} ≈ {estimate_tokens(size)} token")
        return 0

    if not args.paths:
        print("没有要检查的路径（用 --paths 或 --all-tracked）")
        return 0
    paths = [os.path.normpath(path) for path in args.paths]
    return _report(check_paths(repo, paths, rev=args.rev, limit=limit), limit)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except RuntimeError as exc:
        print(f"体积守卫出错：{exc}", file=sys.stderr)
        raise SystemExit(2) from None
